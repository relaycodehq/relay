// Writes mobile/src/ui/math/katex-assets.ts: KaTeX's script, and its style with
// the fonts inlined, for the phone's WebView to typeset a formula with nothing
// fetched. Only woff2 is kept (every phone WebView reads it). Run again after
// changing the katex version in package.json.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dist = fileURLToPath(new URL("../node_modules/katex/dist/", import.meta.url));
const out = fileURLToPath(
  new URL("../mobile/src/ui/math/katex-assets.ts", import.meta.url),
);
const { version } = JSON.parse(readFileSync(`${dist}../package.json`, "utf8"));

const css = readFileSync(`${dist}katex.min.css`, "utf8").replace(
  /src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)[^}]*/g,
  (_, file) =>
    `src:url(data:font/woff2;base64,${readFileSync(dist + file).toString("base64")}) format("woff2")`,
);
if (/\.(?:woff|ttf)\b/.test(css) || /url\(fonts\//.test(css))
  throw new Error("katex.min.css has a font this script doesn't inline");
const js = readFileSync(`${dist}katex.min.js`, "utf8");

writeFileSync(
  out,
  `// Generated by scripts/build-katex-assets.mjs from katex ${version}; do not edit.
export const katexVersion = ${JSON.stringify(version)};
export const katexCss = ${JSON.stringify(css)};
export const katexJs = ${JSON.stringify(js)};
`,
);
console.log(`katex ${version}: ${(css.length + js.length) >> 10} KB written`);
