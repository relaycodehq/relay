// Writes mobile/src/ui/math/katex-assets.ts: KaTeX's script, its style, and
// each font face inlined on its own, for the phone's WebView to typeset a
// formula with nothing fetched; a page takes only the faces its formula needs.
// Only woff2 is kept (every phone WebView reads it). Run again after changing
// the katex version in package.json.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dist = fileURLToPath(new URL("../node_modules/katex/dist/", import.meta.url));
const out = fileURLToPath(
  new URL("../mobile/src/ui/math/katex-assets.ts", import.meta.url),
);
const { version } = JSON.parse(readFileSync(`${dist}../package.json`, "utf8"));

const fonts = {};
const css = readFileSync(`${dist}katex.min.css`, "utf8").replace(
  /@font-face\{[^}]*src:url\(fonts\/KaTeX_([\w-]+)\.woff2\) format\("woff2"\)[^}]*\}/g,
  (face, name) => {
    fonts[name] = face.replace(
      /src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)[^}]*/,
      (_, file) =>
        `src:url(data:font/woff2;base64,${readFileSync(dist + file).toString("base64")}) format("woff2")`,
    );
    return "";
  },
);
if (/@font-face|url\(fonts\//.test(css))
  throw new Error("katex.min.css has a font this script doesn't inline");
const js = readFileSync(`${dist}katex.min.js`, "utf8");

writeFileSync(
  out,
  `// Generated by scripts/build-katex-assets.mjs from katex ${version}; do not edit.
export const katexVersion = ${JSON.stringify(version)};
export const katexCss = ${JSON.stringify(css)};
/** Each font face's \`@font-face\` rule, by its file's name: \`Main-Regular\`, \`AMS-Regular\`… */
export const katexFonts: Record<string, string> = ${JSON.stringify(fonts, null, 1)};
export const katexJs = ${JSON.stringify(js)};
`,
);
const faces = Object.values(fonts).join("").length;
console.log(`katex ${version}: ${(css.length + faces + js.length) >> 10} KB written`);
