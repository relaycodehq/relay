// Rewrites the generated part of THIRD_PARTY_NOTICES.md: the npm packages
// that end up in the desktop app and the phone app, with
// their licence texts, and the Android libraries the phone's native modules
// declare. Everything above the generated marker is written by hand and kept.
//
//   npm ci && npm ci --prefix mobile     (once; the phone list comes from Metro)
//   node scripts/third-party-notices.mjs           rewrite the file
//   node scripts/third-party-notices.mjs --check   exit 1 when it's out of date
//
// Packages are found the way the builds find them: esbuild's metafile for the
// main process and its workers, Vite's chunks for the
// renderer, and Metro's source map for the phone, so what was tree-shaken or
// never imported doesn't show up. Packages the build copies as plain files are
// listed in `copied`. Licences outside `permissive` are printed for review.
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mobile = join(repo, "mobile");
const noticesFile = join(repo, "THIRD_PARTY_NOTICES.md");
const begin =
  "<!-- BEGIN GENERATED by scripts/third-party-notices.mjs; edits below this line are overwritten -->";
const end = "<!-- END GENERATED -->";
process.chdir(repo);

// scripts/build-electron.mjs copies these beside the bundles instead of bundling them.
const copied = ["node-pty", "sherpa-onnx-node"];

// Packages published without a licence file. Some come from a monorepo whose
// licence covers them; others have a hand-written section above the marker.
const licenceOf = {
  "@react-native/assets-registry": { from: "react-native" },
  "@react-native/js-polyfills": { from: "react-native" },
  "@react-native/normalize-colors": { from: "react-native" },
  "@react-native/virtualized-lists": { from: "react-native" },
  "@expo/ui": { from: "expo" },
  "expo-router": { from: "expo" },
  "onnxruntime-common": { above: "ONNX Runtime" },
  "onnxruntime-node": { above: "ONNX Runtime" },
  "sherpa-onnx-node": { above: "sherpa-onnx" },
  "@anthropic-ai/claude-agent-sdk": { above: "Anthropic Claude Agent SDK" },
};

const permissive = new Set(
  [
    "MIT",
    "ISC",
    "0BSD",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "Apache-2.0",
    "BlueOak-1.0.0",
    "CC0-1.0",
    "Unlicense",
    "Python-2.0",
    "Zlib",
  ].map((id) => id.toUpperCase()),
);

/** The package folder a bundled file came from: up to the last node_modules/<name>. */
function packageDir(file, root) {
  const parts = file.split(/[\\/]/);
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return undefined;
  const take = parts[at + 1]?.startsWith("@") ? 3 : 2;
  return resolve(root, parts.slice(0, at + take).join("/"));
}

async function esbuildPackages(entries) {
  const { build } = await import(
    join(repo, "node_modules/esbuild/lib/main.js")
  );
  const dirs = new Set();
  for (const options of entries) {
    const { metafile } = await build({
      ...options,
      write: false,
      metafile: true,
      logLevel: "silent",
    });
    for (const input of Object.keys(metafile.inputs)) {
      const dir = packageDir(input.replace(/^[^:]*:/, ""), repo);
      if (dir) dirs.add(dir);
    }
  }
  return dirs;
}

async function desktopMainPackages() {
  const { bundles } = await import("./electron-bundles.mjs");
  return esbuildPackages([
    ...bundles.map((b) => b.options),
    // build-electron.mjs bundles onnxruntime-node on its own and copies its native addon.
    {
      entryPoints: ["node_modules/onnxruntime-node/dist/index.js"],
      bundle: true,
      platform: "node",
      format: "cjs",
      outfile: "dist-electron/onnxruntime/dist/index.cjs",
      external: ["*.node"],
    },
  ]);
}

async function rendererPackages() {
  const { build } = await import(
    join(repo, "node_modules/vite/dist/node/index.js")
  );
  const dirs = new Set();
  const collect = () => ({
    name: "third-party-notices",
    generateBundle(_, bundle) {
      for (const chunk of Object.values(bundle))
        if (chunk.type === "chunk")
          for (const id of chunk.moduleIds) {
            const dir = packageDir(
              id.replace(/^\0/, "").replace(/\?.*$/, ""),
              repo,
            );
            if (dir) dirs.add(dir);
          }
    },
  });
  await build({
    configFile: join(repo, "vite.config.ts"),
    logLevel: "silent",
    build: { write: false },
    plugins: [collect()],
    worker: { plugins: () => [collect()] },
  });
  return dirs;
}

function phonePackages() {
  if (!existsSync(join(mobile, "node_modules")))
    throw new Error(
      "The phone app's packages aren't installed: run `npm ci --prefix mobile` first.",
    );
  const work = mkdtempSync(join(tmpdir(), "relay-notices-"));
  try {
    const expo = join(
      mobile,
      "node_modules/.bin",
      process.platform === "win32" ? "expo.cmd" : "expo",
    );
    execFileSync(
      expo,
      [
        "export:embed",
        "--platform",
        "android",
        "--dev",
        "false",
        "--minify",
        "false",
        "--entry-file",
        "index.ts",
        "--bundle-output",
        join(work, "index.js"),
        "--sourcemap-output",
        join(work, "index.map"),
        "--assets-dest",
        join(work, "res"),
      ],
      {
        cwd: mobile,
        stdio: "ignore",
        env: { ...process.env, NODE_ENV: "production" },
        shell: process.platform === "win32",
      },
    );
    const { sources } = JSON.parse(
      readFileSync(join(work, "index.map"), "utf8"),
    );
    const dirs = new Set();
    for (const source of sources) {
      // Metro names sources from the app's root, starting with a slash.
      const dir = packageDir(source.replace(/^[\\/]/, ""), mobile);
      if (dir) dirs.add(dir);
    }
    return dirs;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

const licenceFile =
  /^(licen[cs]e|copying|notice|copyright|third[-_ ]?party[-_ ]?notices?)([-._].*)?$/i;

function licenceText(dir) {
  if (!existsSync(dir)) return "";
  return readdirSync(dir)
    .filter(
      (name) => licenceFile.test(name) && statSync(join(dir, name)).isFile(),
    )
    .sort()
    .map((name) =>
      readFileSync(join(dir, name), "utf8")
        .replace(/\r\n?/g, "\n")
        .replace(/[ \t]+$/gm, "")
        .trim(),
    )
    .join("\n\n");
}

/** A README's licence section, when it holds a copyright line: some packages keep their licence there. */
function readmeLicence(dir) {
  const readme = readdirSync(dir).find((name) => /^readme(\.md)?$/i.test(name));
  if (!readme) return "";
  const lines = readFileSync(join(dir, readme), "utf8")
    .replace(/\r\n?/g, "\n")
    .split("\n");
  const start = lines.findIndex((line) => /^#+\s.*licen[cs]e/i.test(line));
  if (start < 0) return "";
  const after = lines.slice(start + 1);
  const stop = after.findIndex((line) => /^#+\s/.test(line));
  const section = (stop < 0 ? after : after.slice(0, stop))
    .join("\n")
    .replace(/[ \t]+$/gm, "")
    .trim();
  return /copyright/i.test(section)
    ? `From the package's README:\n\n${section}`
    : "";
}

/** The licence a package.json without a `license` field means, read from its licence file's first line. */
function licenceFromText(text) {
  const first = text.split("\n", 1)[0];
  if (/\bMIT\b/.test(first)) return "MIT";
  if (/^ISC\b/.test(first)) return "ISC";
  if (/Apache License/.test(first)) return "Apache-2.0";
  return "UNKNOWN";
}

function readPackage(dir) {
  const json = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  let text = licenceText(dir) || readmeLicence(dir);
  let licence = json.license ?? json.licenses ?? licenceFromText(text);
  if (typeof licence === "object")
    licence = [licence]
      .flat()
      .map((l) => l.type ?? l)
      .join(" OR ");
  const instead = licenceOf[json.name];
  if (!text && instead?.from) {
    // The nearest node_modules above the package that holds the monorepo's main package.
    for (let up = dirname(dir); !text && up !== dirname(up); up = dirname(up))
      if (up.endsWith(`${sep}node_modules`))
        text = licenceText(join(up, instead.from));
    if (text)
      text = `No licence file in the package; it is part of ${instead.from}'s repository, whose licence follows.\n\n${text}`;
  }
  if (!text && instead?.above)
    text = `No licence file in the package; see “${instead.above}” in the hand-written part of this file.`;
  const repoUrl =
    typeof json.repository === "string"
      ? json.repository
      : json.repository?.url;
  return {
    name: json.name,
    version: json.version,
    licence: String(licence),
    text,
    source: (
      json.homepage ??
      repoUrl ??
      `https://www.npmjs.com/package/${json.name}`
    )
      .replace(/^git\+/, "")
      .replace(/^ssh:\/\/git@github\.com\//, "https://github.com/")
      .replace(/^git:\/\//, "https://")
      .replace(/\.git$/, "")
      .replace(/^github:/, "https://github.com/"),
  };
}

const key = (p) => `${p.name}@${p.version}`;

function toPackages(dirs) {
  const byKey = new Map();
  for (const dir of dirs) {
    if (!existsSync(join(dir, "package.json"))) continue;
    const pkg = readPackage(dir);
    byKey.set(key(pkg), pkg);
  }
  return [...byKey.values()].sort((a, b) => key(a).localeCompare(key(b), "en"));
}

/** Maven coordinates a phone package's android/build.gradle pulls into the APK. */
function androidLibraries(phoneDirs) {
  const found = new Map();
  for (const dir of phoneDirs) {
    for (const file of ["android/build.gradle", "android/build.gradle.kts"]) {
      const path = join(dir, file);
      if (!existsSync(path)) continue;
      const owner = JSON.parse(
        readFileSync(join(dir, "package.json"), "utf8"),
      ).name;
      for (const line of readFileSync(path, "utf8").split("\n")) {
        if (
          !/^\s*(implementation|api|add\()/.test(line) ||
          /compileOnly|testImplementation/.test(line)
        )
          continue;
        for (const [, coordinate] of line.matchAll(
          /["']([\w.-]+:[\w.-]+)(?::[^"']*)?["']/g,
        )) {
          if (coordinate.startsWith("com.facebook.react:")) continue;
          if (!found.has(coordinate)) found.set(coordinate, new Set());
          found.get(coordinate).add(owner);
        }
      }
    }
  }
  return [...found.entries()].sort(([a], [b]) => a.localeCompare(b, "en"));
}

const escapeCell = (s) => s.replace(/\|/g, "\\|");

function table(packages) {
  return [
    "| Package | Version | Licence |",
    "| --- | --- | --- |",
    ...packages.map(
      (p) =>
        `| ${escapeCell(p.name)} | ${p.version} | ${escapeCell(p.licence)} |`,
    ),
  ].join("\n");
}

function fence(text) {
  const longest = Math.max(
    2,
    ...[...text.matchAll(/`+/g)].map((m) => m[0].length),
  );
  const ticks = "`".repeat(longest + 1);
  return `${ticks}text\n${text}\n${ticks}`;
}

function licenceTexts(packages) {
  // Packages whose licence files are identical share one copy.
  const groups = new Map();
  for (const p of packages) {
    const text =
      p.text ||
      `This package carries no licence file. Its package.json declares: ${p.licence}. Source: ${p.source}`;
    if (!groups.has(text)) groups.set(text, []);
    groups.get(text).push(p);
  }
  return [...groups.entries()]
    .sort(([, a], [, b]) => key(a[0]).localeCompare(key(b[0]), "en"))
    .map(
      ([text, ps]) =>
        `#### ${ps.map((p) => `${p.name} ${p.version}`).join(", ")}\n\n${fence(text)}`,
    )
    .join("\n\n");
}

function isPermissive(licence) {
  return licence
    .replace(/[()]/g, " ")
    .split(/\s+OR\s+/)
    .some((choice) =>
      choice
        .split(/\s+AND\s+/)
        .every((id) => permissive.has(id.trim().toUpperCase())),
    );
}

const [mainDirs, rendererDirs] = [
  await desktopMainPackages(),
  await rendererPackages(),
];
const copiedDirs = copied.map((name) => join(repo, "node_modules", name));
const phoneDirs = phonePackages();

const desktop = toPackages(
  new Set([...mainDirs, ...rendererDirs, ...copiedDirs]),
);
const phone = toPackages(phoneDirs);
const android = androidLibraries(phoneDirs);
const all = toPackages(
  new Set([...mainDirs, ...rendererDirs, ...copiedDirs, ...phoneDirs]),
);

const generated = [
  begin,
  "",
  "## npm packages",
  "",
  "Generated from what the builds actually bundle. Each package's licence text follows the lists, once per package version; packages with identical licence files share one copy.",
  "",
  "### In the desktop app",
  "",
  "The window (bundled by Vite), the main process and its workers (bundled by esbuild), and node-pty and sherpa-onnx-node, which ship as plain files beside them.",
  "",
  table(desktop),
  "",
  "### In the phone app",
  "",
  "The phone app's JavaScript bundle. The desktop app carries the same bundle (`dist-phone/`) to update paired phones.",
  "",
  table(phone),
  "",
  "#### Android libraries",
  "",
  "Declared by the native modules above and compiled into the APK, besides React Native's own (see “Phone app native code” above). Their transitive dependencies aren't listed; they are under the licences their publishers give on Maven.",
  "",
  "| Library | Declared by |",
  "| --- | --- |",
  ...android.map(
    ([coordinate, owners]) =>
      `| ${coordinate} | ${[...owners].sort().join(", ")} |`,
  ),
  "",
  "### Licence texts",
  "",
  licenceTexts(all),
  "",
  end,
  "",
].join("\n");

const current = existsSync(noticesFile)
  ? readFileSync(noticesFile, "utf8")
  : "";
const at = current.indexOf(begin);
const next =
  (at < 0 ? current.trimEnd() + "\n\n" : current.slice(0, at)) + generated;

for (const p of all.filter((p) => !isPermissive(p.licence) || !p.text))
  console.warn(
    `review: ${key(p)}: ${p.licence}${p.text ? "" : ", no licence file"} (${p.source})`,
  );

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error(
      "THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs",
    );
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(noticesFile, next);
  console.log(
    `THIRD_PARTY_NOTICES.md: ${desktop.length} desktop, ${phone.length} phone packages, ${android.length} Android libraries.`,
  );
}
